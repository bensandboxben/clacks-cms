// Builds images/icons.svg, an SVG sprite of the Lucide icons used by the CMS.
// Usage: npm run build:icons   (add new icon names to ICONS below first)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const dir = join(dirname(require.resolve('lucide-static/package.json')), 'icons');

export const ICONS = [
  // shell
  'layout-dashboard', 'house', 'log-out', 'user', 'user-round', 'sun', 'moon', 'menu', 'x', 'search',
  'panel-left-close', 'panel-left-open', 'chevron-down', 'chevron-right', 'chevron-left', 'chevrons-left',
  'chevrons-right', 'external-link', 'book-open', 'circle-help', 'settings', 'command',
  // navigation areas
  'file-text', 'files', 'folder', 'folder-open', 'building-2', 'calendar', 'calendar-days', 'landmark',
  'megaphone', 'newspaper', 'users', 'user-round-pen', 'contact', 'link', 'link-2', 'library', 'school',
  'church', 'scale', 'vote', 'utensils', 'store', 'traffic-cone', 'briefcase', 'image', 'images',
  'chart-bar', 'clipboard-list', 'hard-hat', 'siren', 'heart-handshake', 'star', 'bell', 'globe',
  'list-tree', 'clock', 'layers', 'map', 'tags', 'construction', 'notebook-tabs', 'graduation-cap',
  'ticket', 'monitor', 'panels-top-left', 'square-menu', 'list',
  // actions
  'plus', 'pencil', 'trash-2', 'copy', 'eye', 'info', 'file-pen', 'arrow-up', 'arrow-down',
  'mouse-pointer-click', 'check', 'download', 'upload', 'paperclip', 'save', 'filter', 'rotate-ccw',
  'arrow-up-narrow-wide', 'arrow-down-wide-narrow', 'arrow-up-down', 'mail', 'printer', 'lock',
  'lock-open', 'grip-vertical', 'list-checks', 'square-pen', 'file-down', 'refresh-cw',
  // status
  'circle-check', 'circle-alert', 'triangle-alert', 'circle-x', 'circle-dashed', 'circle', 'circle-dot',
  'inbox', 'badge-check', 'clock-alert', 'calendar-clock', 'activity',
];

const symbols = ICONS.map((name) => {
  const svg = readFileSync(join(dir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '');
  return `<symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`;
});

const sprite = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide icons (ISC licence, https://lucide.dev). Generated by tools/build-icons.mjs - do not edit by hand. -->\n${symbols.join('\n')}\n</svg>\n`;
writeFileSync(new URL('../images/icons.svg', import.meta.url), sprite);
console.log(`images/icons.svg: ${ICONS.length} icons`);
